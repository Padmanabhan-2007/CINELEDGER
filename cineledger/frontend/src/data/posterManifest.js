/**
 * Matches a backend film title (e.g., "Oppenheimer: The Manhattan Chronicles")
 * or explicit posterUrl against the local curated poster manifest so every seeded
 * release displays vivid, dependable local artwork with graceful fallback.
 */
export function resolvePosterAsset(title = '', fallbackUrl = '') {
  const normalized = String(title || '').toLowerCase();
  if (normalized) {
    // Check specific multi-word titles first so "Dune: Part Two" beats "Dune"
    const sorted = [...POSTER_COLLECTION].sort((a, b) => b.title.length - a.title.length);
    const match = sorted.find((item) => normalized.includes(item.title.toLowerCase()));
    if (match) {
      return match.path;
    }
  }
  return fallbackUrl || POSTER_COLLECTION[0].path;
}

